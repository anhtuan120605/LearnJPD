export function getLessonTopic(courseKey: string, lessonNum: number): string {
  if (courseKey === 'MINNA_CHUKYU_1') {
    return CHUKYU_N3_TOPICS[lessonNum] || `Chủ đề N3 chuyên sâu bài ${lessonNum}`;
  }
  if (courseKey === 'MINNA_CHUKYU_2') {
    return CHUKYU_N2_TOPICS[lessonNum] || `Chủ đề N2 chuyên sâu bài ${lessonNum}`;
  }
  if (courseKey === 'JLPT_N1') {
    return JLPT_N1_TOPICS[lessonNum] || `Chủ đề N1 cao cấp bài ${lessonNum}`;
  }
  return MINNA_LESSON_TOPICS[lessonNum] || `Chủ đề bài ${lessonNum}`;
}
