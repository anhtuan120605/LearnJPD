# 6. ĐỌC DỮ LIỆU GỐC VÀ TÁI CẤU TRÚC KANJI N5 -> N1
# -------------------------------------------------------------
kanji_by_char = {}

for lvl in ['n5', 'n4', 'n3', 'n2', 'n1']:
    filepath = f'src/data/kanji/{lvl}.json'
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
        for item in data:
            kanji_by_char[item['kanji']] = item

def get_clean_hanviet(char, fallback_hv):
    if char in STANDARD_HV_MAP:
        return STANDARD_HV_MAP[char]
    if fallback_hv:
        words = fallback_hv.split()
        return words[0].upper()
    return ''

# Tạo tập hợp N5 chuẩn
new_n5_list = []
n5_char_set = set(N5_OFFICIAL_KANJI)

for ch in N5_OFFICIAL_KANJI:
    item = kanji_by_char.get(ch)
    if not item:
        continue

    clean_hv = get_clean_hanviet(ch, item.get('hanviet', ''))
    
    # Lấy ví dụ chuyên gia nếu có
    if ch in N5_EXPERT_COMPOUNDS:
        curated_ex = []
        for w, r, m, hv, lv in N5_EXPERT_COMPOUNDS[ch]:
            curated_ex.append({
                'word': w,
                'reading': r,
                'meaning': m,
                'hanviet': hv,
                'level': lv
            })
        examples = curated_ex
    else:
        # Tìm trong kho từ vựng N5
        matches = [v for v in vocab_by_level['N5'] if ch in v['word']]
        matches = [m for m in matches if len(m['word']) <= 5][:6]
        examples = matches

    new_n5_entry = {
        'id': f'kanji-{ch}',
        'kanji': ch,
        'hanviet': clean_hv,
        'strokes': item.get('strokes', 1),
        'jlpt': 'N5',
        'onyomi': item.get('onyomi', []),
        'kunyomi': item.get('kunyomi', []),
        'meanings_vi': [m.replace('nhất: ', '').replace('nhị: ', '').strip() for m in item.get('meanings_vi', []) if m],
        'meanings_en': item.get('meanings_en', []),
        'radical': item.get('radical', ''),
        'examples': examples
    }
    new_n5_list.append(new_n5_entry)

print(f"-> Chuẩn hóa hoàn tất {len(new_n5_list)} chữ Kanji N5 chuẩn JLPT!")

# Cập nhật N4: Loại bỏ những chữ đã đưa vào N5, sửa Hán Việt & ví dụ
with open('src/data/kanji/n4.json', 'r', encoding='utf-8') as f:
    old_n4 = json.load(f)

new_n4_list = []
for item in old_n4:
    ch = item['kanji']
    if ch in n5_char_set:
        continue # Đã nằm trong N5

    clean_hv = get_clean_hanviet(ch, item.get('hanviet', ''))

    # Làm sạch ví dụ
    clean_examples = []
    for ex in item.get('examples', []):
        m = ex.get('meaning', '')
        if 'hư cấu' in m or 'công suất máy' in m or 'lạc thú' in m or 'kệ thứ' in m:
            continue
        clean_examples.append(ex)

    # Nếu ví dụ bị thiếu, bù đắp từ kho N4/N5
    if len(clean_examples) < 3:
        matches = [v for v in vocab_by_level['N4'] if ch in v['word']]
        for m in matches:
            if not any(e['word'] == m['word'] for e in clean_examples) and len(clean_examples) < 6:
                clean_examples.append(m)

    new_n4_list.append({
        **item,
        'hanviet': clean_hv,
        'examples': clean_examples
    })

print(f"-> Chuẩn hóa hoàn tất {len(new_n4_list)} chữ Kanji N4 chuẩn JLPT!")

